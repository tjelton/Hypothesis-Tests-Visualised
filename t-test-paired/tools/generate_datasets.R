# Generates js/datasets.js for the JS port of the paired t-test lesson.
# Run from the repo root:  Rscript t-test-paired/tools/generate_datasets.R
#
# The five datasets are copied VERBATIM from the Shiny module
# (R/utility_load_data_paired_sample_srv.R). Fidelity notes:
#   * SleepStudy is base R's `sleep`, reshaped wide (built BEFORE set.seed).
#   * The four synthetic sets are seeded with a single set.seed(1) and then
#     built in the SAME ORDER as the R source, because each rnorm() call
#     consumes the shared random stream sequentially -- reordering them (or
#     inserting the set.seed elsewhere) would change every value.
#   * Dataset insertion order below matches the dropdown order in the R module
#     ("BloodPressureStudy", "SleepStudy", ...), which JS preserves as object
#     key order.

library(jsonlite)

# --- SleepStudy: base-R `sleep`, reshaped to wide (no RNG) ---
SleepStudy <- reshape(sleep,
                      timevar = "group",
                      idvar = "ID",
                      direction = "wide")
names(SleepStudy)[names(SleepStudy) == "extra.1"] <- "condition 1"
names(SleepStudy)[names(SleepStudy) == "extra.2"] <- "condition 2"

# --- Synthetic sets: one seed, built in source order ---
set.seed(1)

BloodPressureStudy <- data.frame(
  Before_Treatment = round(rnorm(30, 140, 15), 1),
  After_DrugA = round(rnorm(30, 135, 14), 1),
  After_DrugB = round(rnorm(30, 133, 13), 1)
)

CognitiveScores <- data.frame(
  Baseline_Memory = round(rnorm(30, 75, 8), 0),
  SixMonths_Memory = round(rnorm(30, 80, 7), 0),
  Baseline_Attention = round(rnorm(30, 70, 10), 0),
  SixMonths_Attention = round(rnorm(30, 72, 9), 0)
)

FitnessTestResults <- data.frame(
  VO2Max_Before = round(rnorm(40, 45, 5), 1),
  VO2Max_After = round(rnorm(40, 49, 5), 1),
  SprintTime_Before = round(rnorm(40, 12.0, 0.8), 2),
  SprintTime_After = round(rnorm(40, 11.5, 0.7), 2)
)

DietImpactStudy <- data.frame(
  Weight_Before = round(rnorm(25, 85, 12), 1),
  Weight_After = round(rnorm(25, 80, 11), 1),
  Cholesterol_Before = round(rnorm(25, 200, 25), 0),
  Cholesterol_After = round(rnorm(25, 185, 20), 0)
)

# Emit only the numeric columns (as the R module does via sapply(is.numeric)),
# in the dropdown order.
emit_numeric_cols <- function(df) {
  cols <- list()
  for (cn in names(df)) {
    col <- df[[cn]]
    if (is.numeric(col)) {
      cols[[length(cols) + 1]] <- list(name = cn, type = "numeric", values = col)
    }
  }
  list(columns = cols)
}

out <- list()
for (nm in c("BloodPressureStudy", "SleepStudy", "CognitiveScores",
             "FitnessTestResults", "DietImpactStudy")) {
  out[[nm]] <- emit_numeric_cols(get(nm))
}

json <- toJSON(out, digits = NA, auto_unbox = TRUE, pretty = FALSE)
header <- paste0(
  "// Generated by tools/generate_datasets.R -- do not edit by hand.\n",
  "// Paired datasets copied verbatim from R/utility_load_data_paired_sample_srv.R.\n",
  "// SleepStudy = base R `sleep` reshaped wide; the other four are synthetic\n",
  "// (single set.seed(1), built in source order so the RNG stream matches R).\n"
)
writeLines(paste0(header, "const DATASETS = ", json, ";\n"),
           "t-test-paired/js/datasets.js")
cat("Wrote t-test-paired/js/datasets.js\n")
