# Generates js/datasets.js for the JS port of the regression t-test lesson.
# Run from the repo root:  Rscript t-test-regression/tools/generate_datasets.R
#
# The loader offers six datasets (R/utility_load_data_regression_2_variable_srv.R):
# the synthetic `study_data` plus five from R's `datasets` package. Numeric
# columns are emitted (with NA -> null so the JS can drop incomplete pairs, as
# R's lm() does via na.omit); factor columns are emitted for the optional
# "separate by categorical variable" filter (only iris has one here).

library(jsonlite)

# --- study_data: synthetic, exactly as the Shiny module builds it ---
set.seed(1)
n <- 25
Minutes_Studied <- round(runif(n, min = 0, max = 600), 0)
Test_Score <- round(50 + 0.075 * Minutes_Studied + rnorm(n, mean = 0, sd = 5), 1)
study_data <- data.frame(Minutes_Studied = Minutes_Studied, Test_Score = Test_Score)

emit_cols <- function(df) {
  cols <- list()
  for (cn in names(df)) {
    col <- df[[cn]]
    if (is.numeric(col)) {
      # jsonlite writes NA as null; JS treats null as missing.
      cols[[length(cols) + 1]] <- list(name = cn, type = "numeric", values = col)
    } else if (is.factor(col)) {
      cols[[length(cols) + 1]] <- list(name = cn, type = "categorical",
                                        values = as.character(col))
    }
  }
  list(columns = cols)
}

out <- list()
out[["study_data"]] <- emit_cols(study_data)
for (nm in c("iris", "mtcars", "trees", "airquality", "pressure")) {
  out[[nm]] <- emit_cols(get(nm, envir = as.environment("package:datasets")))
}

json <- toJSON(out, digits = NA, auto_unbox = TRUE, pretty = FALSE, na = "null")
header <- paste0(
  "// Generated by tools/generate_datasets.R -- do not edit by hand.\n",
  "// study_data = synthetic (set.seed(1); Minutes_Studied ~ U(0,600),\n",
  "// Test_Score = 50 + 0.075*Minutes + N(0,5)); the other five are from R's\n",
  "// `datasets` package. NA numeric values are null; JS drops incomplete pairs.\n"
)
writeLines(paste0(header, "const DATASETS = ", json, ";\n"),
           "T-Tests/t-test-regression/js/datasets.js")
cat("Wrote t-test-regression/js/datasets.js\n")
