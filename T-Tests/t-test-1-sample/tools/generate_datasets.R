# Generates js/datasets.js for the JS port of the 1-sample t-test lesson.
# Run from the repo root:  Rscript t-test-1-sample/tools/generate_datasets.R
#
# The exported values are copied verbatim from R's `datasets` package
# (distributed with R under GPL; the underlying values are decades-old
# published scientific measurements). "Mr. Han's Exam Marks" reproduces the
# seeded sample used by the Shiny app (utility_load_data_1_sample_srv.R):
#   set.seed(1); rnorm(25, mean = 142, sd = 5)

library(jsonlite)

set.seed(1)
han <- rnorm(25, mean = 142, sd = 5)

out <- list()
out[["Mr. Han's Exam Marks"]] <- list(
  columns = list(list(name = "Scores", type = "numeric", values = han))
)

for (nm in c("iris", "Orange", "PlantGrowth", "ToothGrowth", "chickwts", "ChickWeight")) {
  df <- get(nm, envir = as.environment("package:datasets"))
  cols <- list()
  for (cn in names(df)) {
    col <- df[[cn]]
    if (is.numeric(col)) {
      cols[[length(cols) + 1]] <- list(name = cn, type = "numeric", values = col)
    } else if (is.factor(col)) {
      cols[[length(cols) + 1]] <- list(
        name = cn, type = "factor",
        values = as.character(col), levels = levels(col)
      )
    } else {
      cols[[length(cols) + 1]] <- list(name = cn, type = "other", values = as.character(col))
    }
  }
  out[[nm]] <- list(columns = cols)
}

json <- toJSON(out, digits = NA, auto_unbox = TRUE, pretty = FALSE)
header <- paste0(
  "// Generated by tools/generate_datasets.R -- do not edit by hand.\n",
  "// Sources: R `datasets` package (iris: Anderson 1935/Fisher 1936; Orange: Draper & Smith;\n",
  "// PlantGrowth: Dobson 1983; ToothGrowth: Crampton 1947; chickwts: McNeil 1977;\n",
  "// ChickWeight: Crowder & Hand 1990). Mr. Han's Exam Marks = set.seed(1); rnorm(25, 142, 5).\n"
)
writeLines(paste0(header, "const DATASETS = ", json, ";\n"),
           "T-Tests/t-test-1-sample/js/datasets.js")
cat("Wrote t-test-1-sample/js/datasets.js\n")
