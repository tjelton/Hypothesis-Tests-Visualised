# Generates js/datasets.js for the JS port of the 2-sample t-test lesson.
# Run from the repo root:  Rscript t-test-2-sample/tools/generate_datasets.R
#
# The lesson's data loader offers six datasets (see
# R/utility_load_data_2_sample_srv.R): the synthetic `blood_pressure` set plus
# five from R's `datasets` package. For each we emit every column typed as
# "numeric" or "categorical" (categorical = factor OR character with >= 2
# unique values, matching the loader's column filters). Categorical values are
# emitted in row order so the JS can reproduce R's unique()-in-appearance-order
# for the sample selectors.

library(jsonlite)

# --- blood_pressure: synthetic, exactly as the Shiny module builds it ---
set.seed(1)
n <- 50
blood_pressure <- data.frame(
  drug = rep(c("Drug_A", "Drug_B"), each = n),
  blood_pressure = c(
    rnorm(n, mean = 120, sd = 10),
    rnorm(n, mean = 115, sd = 10)
  )
)

emit_cols <- function(df) {
  cols <- list()
  for (cn in names(df)) {
    col <- df[[cn]]
    if (is.numeric(col)) {
      cols[[length(cols) + 1]] <- list(name = cn, type = "numeric", values = col)
    } else if (is.factor(col) || is.character(col)) {
      cols[[length(cols) + 1]] <- list(name = cn, type = "categorical",
                                        values = as.character(col))
    }
  }
  list(columns = cols)
}

out <- list()
out[["blood_pressure"]] <- emit_cols(blood_pressure)
for (nm in c("iris", "InsectSprays", "CO2", "ToothGrowth", "PlantGrowth")) {
  out[[nm]] <- emit_cols(get(nm, envir = as.environment("package:datasets")))
}

json <- toJSON(out, digits = NA, auto_unbox = TRUE, pretty = FALSE)
header <- paste0(
  "// Generated by tools/generate_datasets.R -- do not edit by hand.\n",
  "// blood_pressure = synthetic (set.seed(1); two rnorm groups of 50); the other\n",
  "// five are from R's `datasets` package. Columns typed numeric/categorical;\n",
  "// categorical values kept in row order for unique()-in-appearance-order.\n"
)
writeLines(paste0(header, "const DATASETS = ", json, ";\n"),
           "t-test-2-sample/js/datasets.js")
cat("Wrote t-test-2-sample/js/datasets.js\n")
